#!/usr/bin/env bun
// Run with $WAKU_BUN_EXECUTABLE. Bun.Image resizes the original artwork;
// FFmpeg normalizes the artwork, adds the microphone, retains a white
// foreground with transparent cutouts/background, then emits firmware RGB565.
import { copyFileSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { generateGoVoiceAppIcon } from './generate-go-voice-app-icon.mjs';

const root = resolve(import.meta.dir, '..');
const source = resolve(root, 'assets/brand/go-voice-logo.png');
const artwork = resolve(root, 'assets/brand/go-voice-gopher-source.png');
const microphone = resolve(root, 'assets/brand/go-voice-microphone.png');
if (typeof Bun.Image !== 'function') {
  throw new Error('Run with $WAKU_BUN_EXECUTABLE: this generator requires Bun.Image.');
}
const temporaryDirectory = mkdtempSync(join(tmpdir(), 'go-voice-logo-'));
let pixels;
try {
  const scaled = join(temporaryDirectory, 'scaled.png');
  const normalized = join(temporaryDirectory, 'normalized.png');
  await new Bun.Image(artwork).resize(1024, 1024).png().write(scaled);
  // Normalize the existing white-on-black design before mapping its white
  // coverage into alpha. The final artwork has white RGB and no background.
  // Retain the previous tile mask so the conversion preserves edge coverage.
  const alpha = '255*clip(216.5-hypot(max(abs(X-511.5)-248,0),max(abs(Y-511.5)-248,0)),0,1)';
  const normalize = spawnSync('ffmpeg', [
    '-v', 'error', '-i', scaled, '-i', microphone,
    '-filter_complex',
    `[0:v]format=rgba[art];color=c=black:s=1024x1024,format=rgba[bg];` +
    `[bg][art]overlay=shortest=1,format=gray,lut=y='clip((val-48)*255/160,0,255)',` +
    `format=rgba,geq=r='r(X,Y)':g='g(X,Y)':b='b(X,Y)':a='${alpha}',format=rgba[base];` +
    `[base][1:v]overlay=shortest=1:format=auto,format=rgba[whiteLogo];` +
    `[whiteLogo]geq=r=255:g=255:b=255:a='alpha(X,Y)*r(X,Y)/255',format=rgba[out]`,
    '-map', '[out]', '-frames:v', '1', normalized
  ], { encoding: 'utf8' });
  if (normalize.status !== 0) throw new Error(normalize.stderr || String(normalize.error));
  copyFileSync(normalized, source);
  await generateGoVoiceAppIcon();
  const resized = join(temporaryDirectory, 'resized.png');
  await new Bun.Image(source).resize(64, 64).png().write(resized);
  // Bun.Image has no raw RGB565 output; FFmpeg only composites and converts.
  const result = spawnSync('ffmpeg', [
    '-v', 'error', '-i', resized,
    '-filter_complex',
    '[0:v]format=rgba[logo];color=c=0x0B1018:s=64x64,format=rgba[bg];[bg][logo]overlay=shortest=1,format=rgb565le[out]',
    '-map', '[out]', '-frames:v', '1', '-f', 'rawvideo', 'pipe:1'
  ], { maxBuffer: 1024 * 1024 });
  if (result.status !== 0) throw new Error(result.stderr?.toString() || String(result.error));
  pixels = result.stdout;
} finally {
  rmSync(temporaryDirectory, { recursive: true, force: true });
}
if (pixels.length !== 64 * 64 * 2) throw new Error(`Unexpected raster size: ${pixels.length}`);
const rows = [];
for (let offset = 0; offset < pixels.length; offset += 16) {
  rows.push('    ' + [...pixels.subarray(offset, offset + 16)].map(n => `0x${n.toString(16).padStart(2, '0')}`).join(', ') + ',');
}
const output = resolve(root, 'assets/brand/go_voice_logo_asset.h');
mkdirSync(resolve(root, 'assets/brand'), { recursive: true });
const sourceHash = new Bun.CryptoHasher('sha256').update(readFileSync(source)).digest('hex');
writeFileSync(output, `#pragma once\n#include <stdint.h>\n\n/* Go Voice white-on-transparent Gopher and microphone artwork. Generated by tools/generate-go-voice-logo.mjs.\n * Source SHA-256: ${sourceHash}\n * 64x64 RGB565 little-endian, alpha composited onto UI_BG (#0B1018).\n * 8192 constant bytes; no runtime resize, decode, or heap allocation.\n */\nstatic const uint8_t s_go_voice_logo_data[8192] = {\n${rows.join('\n')}\n};\n`);
console.log(`Generated ${output}: ${pixels.length} bytes`);
